package com.lxisoft.garage.model;

public class Vehicle
{
	private String brand;
	private String model;
	private String registerNo;
	private float milege;
	private boolean insurence;

		
	public void setBrand(String brand)
	{
		this.brand=brand;
	}
	
	
	public String getBrand()
	{
		return brand;
	}
	
	
	
	
	public void setModel(String model)
	{
		this.model=model;
	}
	
	
	public String getModel()
	{
		return model;
	}
	
	
	
	
	public void setRegisterno(String no)
	{
		this.registerNo=no;
	}
	
	
	public String getRegisterno()
	{
		return registerNo;
	}
	
	
	
	
	
	public void setMileage(int milege)
	{
		this.milege=milege;
	}
	
	
	public float getMileage()
	{
		return milege;
	}
	
	
	
	
	
	public void setInsurence(boolean insu)
	{
		this.insurence=insu;
	}
	
	
	public boolean getInsurence()
	{
		return insurence;
	}
	

	
}
	
	

	
	
	
	
	

	
	
	
	
	
	
	
	
	
	
	
	
	
	